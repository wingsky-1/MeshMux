package node

// Runtime error codes are a closed set.
//
// Every code that can reach a TaskResult, a log line or an operator-facing
// detail is registered here. A value that is not registered never becomes an
// error code: the runtime reports taskFailedCode instead, so an arbitrary
// message cannot smuggle a path, a digest or free-form text into the operator
// contract. Runtime values (paths, hashes, exit codes) go to log fields only.
//
// The registry is the single source of truth for this package: adding a code
// means adding it here, which is what keeps "stable code" from silently
// becoming "whatever the error happened to say".

// taskFailedCode is the fail-closed replacement for an unregistered value.
const taskFailedCode = "TASK_FAILED"

